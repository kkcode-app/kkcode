export function isTextPreviewableFile(filename: string): boolean {
  const name = filename.toLowerCase();
  if (TEXT_FILENAMES.has(name) || name.startsWith(".env")) return true;
  const extension = name.split(".").pop();
  return Boolean(extension && TEXT_EXTENSIONS.has(extension));
}

export function isMarkdownFile(filename: string): boolean {
  const lower = filename.toLowerCase();
  return lower.endsWith(".md") || lower.endsWith(".mdx") || lower.endsWith(".markdown");
}

export function isImagePreviewableFile(filename: string): boolean {
  const extension = filename.toLowerCase().split(".").pop();
  return Boolean(extension && IMAGE_EXTENSIONS.has(extension));
}
